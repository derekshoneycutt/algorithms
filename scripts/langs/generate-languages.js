#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "..", "..");
const SOURCE_FILE_PATH = path.join(REPO_ROOT, "templates", "languages.source.json");
const GENERATED_SHELL_PATH = path.join(REPO_ROOT, "shlib", "generated", "languages.generated.sh");
const GENERATED_EXTENSION_PATH = path.join(
  REPO_ROOT,
  "extension",
  "src",
  "languages",
  "generated",
  "languages.generated.ts"
);

/**
 * Reads the canonical language source JSON.
 *
 * @returns {{contracts: object, languages: Array<object>}} Source payload.
 */
function readSource() {
  const text = fs.readFileSync(SOURCE_FILE_PATH, "utf8");
  return JSON.parse(text);
}

/**
 * Writes one file atomically.
 *
 * @param {string} filePath Output file path.
 * @param {string} content File content.
 * @returns {void}
 */
function writeFileAtomic(filePath, content) {
  const directory = path.dirname(filePath);
  fs.mkdirSync(directory, { recursive: true });

  const tempFilePath = path.join(
    directory,
    `.${path.basename(filePath)}.${process.pid}.${Date.now()}.tmp`
  );

  fs.writeFileSync(tempFilePath, content);
  fs.renameSync(tempFilePath, filePath);
}

/**
 * Escapes one string for safe single-quoted shell output.
 *
 * @param {string} value Raw value.
 * @returns {string} Shell-safe single-quoted string.
 */
function toShellSingleQuoted(value) {
  return `'${String(value).replace(/'/g, `'"'"'`)}'`;
}

/**
 * Builds shell script content for generated language metadata.
 *
 * @param {{contracts: {managedProfileMarkers: {start: string, end: string}, managedProfileExports: string[], routeFormats: {docker: {mapEntryPattern: string}, ssh: {legacy: {fieldCount: number, separator: string}, explicit: {fieldCount: number, separator: string}}}}, languages: Array<{key: string, extension: string, sampleOutputTemplate: string, smoke: {defaultEnabled: boolean}, displayLabel: string, icon: {fileName: string}, aliases: {languageIds: string[], fileExtensions: string[]}, constraints: {canRun: Array<{platform: string[], arch: string[], note?: string}>}}>} source Source payload.
 * @returns {string} Generated shell file content.
 */
function buildShellContent(source) {
  const lines = [];

  lines.push("#!/usr/bin/env bash");
  lines.push("# AUTO-GENERATED by npm run langsupdate. DO NOT EDIT.");
  lines.push("");
  lines.push("get_generated_language_catalog() {");
  lines.push("  cat <<'EOF'");

  for (const language of source.languages) {
    lines.push(`${language.key}|${language.extension}|${language.sampleOutputTemplate}`);
  }

  lines.push("EOF");
  lines.push("}");
  lines.push("");
  lines.push("get_generated_supported_language_keys() {");
  lines.push("  get_generated_language_catalog | awk -F'|' '{print $1}'");
  lines.push("}");
  lines.push("");

  const smokeKeys = source.languages
    .filter((language) => Boolean(language.smoke && language.smoke.defaultEnabled))
    .map((language) => language.key)
    .join(" ");

  lines.push(`GENERATED_SMOKE_DEFAULT_KEYS=${toShellSingleQuoted(smokeKeys)}`);
  lines.push(
    `GENERATED_PROFILE_BLOCK_START=${toShellSingleQuoted(source.contracts.managedProfileMarkers.start)}`
  );
  lines.push(
    `GENERATED_PROFILE_BLOCK_END=${toShellSingleQuoted(source.contracts.managedProfileMarkers.end)}`
  );
  lines.push(
    `GENERATED_ROUTE_DOCKER_PATTERN=${toShellSingleQuoted(source.contracts.routeFormats.docker.mapEntryPattern)}`
  );
  lines.push(
    `GENERATED_ROUTE_SSH_LEGACY_FIELDS=${toShellSingleQuoted(String(source.contracts.routeFormats.ssh.legacy.fieldCount))}`
  );
  lines.push(
    `GENERATED_ROUTE_SSH_EXPLICIT_FIELDS=${toShellSingleQuoted(String(source.contracts.routeFormats.ssh.explicit.fieldCount))}`
  );
  lines.push("");
  lines.push("get_generated_managed_profile_exports() {");
  lines.push("  cat <<'EOF'");
  for (const exportName of source.contracts.managedProfileExports) {
    lines.push(exportName);
  }
  lines.push("EOF");
  lines.push("}");

  return `${lines.join("\n")}\n`;
}

/**
 * Builds TS module content for generated language metadata used by vscextension.
 *
 * @param {{schemaVersion: number, catalogVersion: string, defaults: object, contracts: object, languages: Array<object>}} source Source payload.
 * @returns {string} Generated TS module content.
 */
function buildExtensionContent(source) {
  const payload = {
    schemaVersion: source.schemaVersion,
    catalogVersion: source.catalogVersion,
    defaults: source.defaults,
    contracts: source.contracts,
    languages: source.languages,
  };

  return [
    "// AUTO-GENERATED by npm run langsupdate. DO NOT EDIT.",
    "",
    'import type { GeneratedLanguageData } from "../generatedTypes";',
    "",
    `export const GENERATED_LANGUAGE_DATA: GeneratedLanguageData = ${JSON.stringify(payload, null, 2)};`,
    "",
  ].join("\n");
}

/**
 * Runs artifact generation.
 *
 * @returns {number} Exit code.
 */
function generate() {
  try {
    const source = readSource();
    const shellContent = buildShellContent(source);
    const extensionContent = buildExtensionContent(source);

    writeFileAtomic(GENERATED_SHELL_PATH, shellContent);
    writeFileAtomic(GENERATED_EXTENSION_PATH, extensionContent);

    console.log(`Generated ${path.relative(REPO_ROOT, GENERATED_SHELL_PATH)}`);
    console.log(`Generated ${path.relative(REPO_ROOT, GENERATED_EXTENSION_PATH)}`);
    return 0;
  } catch (error) {
    console.error("Language artifact generation failed:");
    console.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
}

process.exit(generate());
